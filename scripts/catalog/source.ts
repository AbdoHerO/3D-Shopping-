export interface ArtSpec {
  body: string
  cap?: string
  label?: string
  ink?: string
  accent?: string
  /** Visual sub-style of the shape (e.g. different perfume flacons). */
  style?: number
  /** Glass containers show a liquid of this colour. */
  liquid?: string
  /** Short text printed on the pack (packaging language: French). */
  line?: string
}

export interface VariantSource {
  id: string
  name: I18nText
  colorHex?: string
  price?: number
  promoPrice?: number
  stock?: number
}

export interface ProductSource {
  slug: string
  category: string
  brand: string
  name: I18nText
  description: I18nText
  size: string
  price: number
  promoPrice?: number
  stock?: number
  shape: ArtShape
  /** width × height × depth in cm */
  dims: [number, number, number]
  /** Merchandising hint from the first layout: products are listed in this order when placed automatically. */
  at: [fixtureId: string, level: number, slot: number, facings?: number]
  art: ArtSpec
  variants?: VariantSource[]
  displayVariants?: boolean
  featured?: boolean
  isNew?: boolean
}

