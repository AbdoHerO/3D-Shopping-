/**
 * Writes supabase/seed.sql from public/data/catalog.json so a fresh Supabase project starts with
 * the same catalog as the demo. Product images keep their relative paths (products/x.webp), which
 * the app serves itself; photos uploaded later from the admin get full storage URLs.
 *
 *   npx tsx scripts/generate-seed-sql.ts
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { productToRow, variantToRow, zoneToRow } from '../src/lib/supabase-mapping'
import type { Catalog } from '../src/lib/types'

const q = (v: unknown): string => {
  if (v === null || v === undefined) return 'null'
  if (typeof v === 'number') return String(v)
  if (typeof v === 'boolean') return v ? 'true' : 'false'
  if (Array.isArray(v) && v.every((x) => typeof x === 'string')) return `array[${v.map(q).join(', ')}]::text[]`
  if (typeof v === 'object') return `${q(JSON.stringify(v))}::jsonb`
  return `'${String(v).replace(/'/g, "''")}'`
}

function insert(table: string, rows: Record<string, unknown>[], conflict = 'id') {
  if (rows.length === 0) return ''
  const cols = Object.keys(rows[0])
  const values = rows.map((r) => `  (${cols.map((c) => (Array.isArray(r[c]) && (r[c] as unknown[]).length === 0 ? "'{}'::text[]" : q(r[c]))).join(', ')})`)
  const updates = cols.filter((c) => !conflict.split(',').map((x) => x.trim()).includes(c)).map((c) => `${c} = excluded.${c}`)
  return `insert into public.${table} (${cols.join(', ')}) values\n${values.join(',\n')}\non conflict (${conflict}) do update set ${updates.join(', ')};\n`
}

export function seedSql(catalog: Catalog) {
  const out = ['-- Generated by scripts/generate-seed-sql.ts from public/data/catalog.json', 'begin;']
  out.push(insert('settings', [{ id: 1, data: catalog.settings }]))
  out.push(insert('categories', catalog.categories.map((c) => ({ id: c.id, slug: c.slug, name: c.name, sort: c.sort }))))
  out.push(insert('delivery_zones', catalog.deliveryZones.map((z, i) => zoneToRow(z, i) as unknown as Record<string, unknown>)))
  out.push(insert('products', catalog.products.map((p) => productToRow(p) as unknown as Record<string, unknown>)))
  const variants = catalog.products.flatMap((p) => p.variants.map((v, i) => variantToRow(p.id, v, i) as unknown as Record<string, unknown>))
  out.push(insert('product_variants', variants, 'product_id, id'))
  out.push('commit;')
  return out.join('\n')
}

if (process.argv[1]?.endsWith('generate-seed-sql.ts')) {
  const catalog = JSON.parse(readFileSync('public/data/catalog.json', 'utf8')) as Catalog
  writeFileSync('supabase/seed.sql', seedSql(catalog))
  console.log(`supabase/seed.sql: ${catalog.products.length} products`)
}
